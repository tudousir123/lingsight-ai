const { chromium } = require('@playwright/test')
const path = require('node:path')
;(async () => {
  const browser = await chromium.launch({headless: true})
  const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } })
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  await page.addInitScript(() => {
    localStorage.setItem('access_token', 'preview-only')
    localStorage.setItem('lingsight.onboarding-seen.v1', '1')
    localStorage.setItem('vite-ui-theme', 'dark')
  })
  await page.route('**/api/v1/users/me', r => r.fulfill({json: {id: 'preview', full_name: '研究者', email: 'researcher@example.com', is_active: true, is_superuser: false}}))
  await page.route('**/api/v1/agent/tasks', r => r.fulfill({json: [{id: 'preview-task', title: '空间学习 · 轨迹探索', created_at: '2026-11-10T02:00:00Z', runs: [{id: 'preview-run', status: 'succeeded'}], artifacts: []}]}))
  await page.goto('http://localhost:5173/')
  await page.getByRole('heading', {name: '从实验数据，开启新的探索。'}).waitFor()
  await page.getByRole('link', {name: /继续任务：/}).waitFor()
  await page.screenshot({path: path.join(__dirname, 'desktop-1600-zh-v1.png')})
  for (const [width, height] of [[1440,900], [1280,720], [1920,1080]]) {
    await page.setViewportSize({width, height})
    await page.screenshot({path: path.join(__dirname, `desktop-${width}-zh-v1.png`)})
    const layout = await page.evaluate(() => ({overflow: document.documentElement.scrollWidth > innerWidth, input: document.querySelector('.agent-composer').getBoundingClientRect().toJSON()}))
    if (layout.overflow || layout.input.bottom > height) throw new Error(`Layout failed at ${width}: ${JSON.stringify(layout)}`)
  }
  let writes = 0
  page.on('request', r => {if (r.method() === 'POST') writes++})
  await page.getByRole('button', {name: /探索实验数据/}).click()
  const input = page.getByRole('textbox', {name: '研究问题', exact: true})
  if (!(await input.inputValue()).includes('不同批次分开分析')) throw new Error('Research card did not populate scoped prompt')
  if (!(await input.evaluate(el => el === document.activeElement))) throw new Error('Research card did not focus composer')
  if (writes) throw new Error('Example submitted automatically')
  await page.getByRole('link', {name: /汇集你的研究成果/}).click()
  await page.getByRole('heading', {name: '分析与报告', exact: true}).waitFor()
  await page.goto('http://localhost:5173/')
  await page.getByRole('link', {name: /找到你的研究起点/}).click()
  await page.waitForURL('**/onboarding')
  console.log('Entry interactions: research card populates and focuses draft without submission; report and guide cards navigate to existing pages.')
  if (errors.length) throw new Error(errors.join('\n'))
  console.log('Desktop previews: 1280×720, 1440×900, 1600×1000, 1920×1080. No horizontal overflow or composer clipping; no page errors. Synthetic preview data only.')
  await browser.close()
})().catch(e => {console.error(e); process.exitCode = 1})
