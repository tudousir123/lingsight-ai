const { chromium } = require(process.env.E2E_PLAYWRIGHT_MODULE)
const assert = require('node:assert/strict')
;(async () => {
  const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', headless: true, args: ['--no-sandbox'] })
  const page = await browser.newPage({ acceptDownloads: true, viewport: { width: 1440, height: 900 } })
  page.setDefaultTimeout(45000)
  const errors=[]
  page.on('pageerror', e => errors.push(e.message))
  await page.addInitScript(() => localStorage.setItem('lingsight.onboarding-seen.v1', '1'))
  try {
    await page.goto(process.env.E2E_WEB_URL + '/login')
    await page.getByTestId('email-input').fill('admin@example.com')
    await page.getByTestId('password-input').fill('synthetic-test-password')
    await page.getByRole('button', { name: 'Log In' }).click()
    await page.getByRole('textbox', { name: '研究问题', exact: true }).waitFor()
    const goal = `This is a fictional software acceptance test. First call request_clarification to ask whether the user confirms using synthetic-video, then stop and wait. After confirmation, read the synthetic skill. Query SELECT dataset_key, sample_rate, sample_count, valid_count FROM training_fixture.sample_sets WHERE dataset_key = 'synthetic-video' LIMIT 1 and SELECT sample_no, signal_value, synthetic_flag, fake_x, fake_y, fake_a, fake_b FROM training_fixture.sample_points WHERE dataset_key = 'synthetic-video' ORDER BY sample_no LIMIT 10. Run Python; divide sample_no by 30 and preserve signal_value. Assert elapsed seconds [0,1,2] and signal values [359,1,90]. Produce observations.csv with columns sample_no,elapsed_s,signal_value, PNG and SVG scatter plots with English labels, and a substantive report marked SYNTHETIC SOFTWARE ACCEPTANCE ONLY with provenance and no scientific claims. No further clarification is needed.`
    await page.getByRole('textbox', { name: '研究问题', exact: true }).fill(goal)
    await page.getByRole('button', { name: '发送研究问题' }).click()
    await page.waitForURL(/\/tasks\/[0-9a-f-]+/, { timeout: 45000 })
    const task = page.url().split('/tasks/')[1].split(/[?#]/)[0]
    await page.getByRole('textbox', { name: '补充研究口径' }).waitFor({ timeout: 240000 })
    await page.getByRole('textbox', { name: '补充研究口径' }).fill('Confirm synthetic-video; all values are synthetic.')
    await page.getByRole('button', { name: '确认并继续' }).click()
    await page.locator('.agent-run-status.status-succeeded').waitFor({ timeout: 600000 })
    const snapshot = await page.evaluate(async (id) => {
      const token = localStorage.getItem('access_token')
      const r = await fetch(`/api/v1/agent/tasks/${id}`, { headers: { authorization: `Bearer ${token}` } })
      if (!r.ok) throw new Error(`snapshot HTTP ${r.status}`)
      return r.json()
    }, task)
    const report = snapshot.artifacts.find(a => a.kind === 'report')
    assert.ok(report, 'report was delivered')
    assert.ok(snapshot.artifacts.some(a => a.kind === 'data'))
    assert.ok(snapshot.artifacts.some(a => a.name.endsWith('.png')))
    assert.ok(snapshot.artifacts.some(a => a.name.endsWith('.svg')))
    assert.ok(snapshot.artifacts.some(a => a.name === 'observations.csv'))
    await page.getByRole('button', { name: new RegExp(report.name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')) }).first().click()
    await page.getByRole('button', { name: '编辑报告' }).click()
    const editor = page.getByRole('textbox', { name: '报告 Markdown' })
    const original = await editor.inputValue()
    await editor.fill(original + '\n\nSynthetic browser acceptance edit.\n')
    await page.getByRole('button', { name: '保存为新版本' }).click()
    await page.getByRole('dialog').waitFor({ state: 'hidden' })
    const downloadPromise = page.waitForEvent('download')
    await page.getByRole('button', { name: '下载材料包' }).click()
    const download = await downloadPromise
    await download.saveAs(process.env.E2E_BUNDLE_PATH)
    await page.reload()
    await page.locator('.agent-run-status.status-succeeded').waitFor({ timeout: 45000 })
    assert.deepEqual(errors, [])
    console.log(JSON.stringify({status:'passed',checks:['login','create task','clarification and answer','Pi and Python completion','report edit','ZIP download','reload'],data:'synthetic MCP fixture only',artifact_count:snapshot.artifacts.length}))
  } catch (e) { console.error(JSON.stringify({url:page.url(), body:(await page.locator("body").innerText()).slice(0,1200), pageErrors:errors})); throw e } finally { await browser.close() }
})().catch(e => { console.error(e.stack); process.exitCode = 1 })
